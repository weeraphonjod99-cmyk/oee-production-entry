const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const ts = require('typescript');
const path = require('node:path');
const code = ts.transpileModule(fs.readFileSync(path.join(__dirname, '../src/lib/capacityMatching.ts'), 'utf8'), {compilerOptions:{target:ts.ScriptTarget.ES2022,module:ts.ModuleKind.CommonJS}}).outputText;
const mod = {exports:{}};
vm.runInNewContext(code, {exports:mod.exports, module:mod});
const match = mod.exports.createCapacityMatcher;
const machine = {id:'m7', name:'7# GTX-300T'};
const record = {sheetName:machine.name,machineName:machine.name,partNo:'BRU30888',productName:'METAL BOX 8/10 WAY',step:'',kpi85PerMinute:2.975};
const data = records => ({machines:[{sheetName:machine.name,machineName:machine.name,records}]});
const log = {machineId:machine.id,machineName:machine.name,partNo:'NMS/BRU30888',productName:'METAL BOX 8/10 WAY',step:'3/5'};
const resolve = (records, l=log, percent=85) => match(data(records),[machine],percent)(l);
for(const step of ['3/5','4/5','5/5']) assert.equal(resolve([record],{...log,step}).rate,2.975);
assert.equal(resolve([record],{...log,partNo:' nms / BRU30888 '}).rate,2.975);
assert.equal(resolve([record],{...log,partNo:'XYZ30888'}).rate,null,'same digits do not establish the same part');
assert.equal(resolve([record],{...log,partNo:'BRU30888-AA'}).rate,null,'do not strip arbitrary revisions');
assert.equal(resolve([record],{...log,machineName:'8# GTX-500T'}).rate,null,'never borrow another machine target');
assert.equal(resolve([{...record,machineNo:'8#'}]).rate,null);
assert.equal(resolve([{...record,machineType:'500T'}]).rate,null);
assert.equal(resolve([record,record]).rate,2.975,'identical duplicates do not multiply target');
assert.equal(resolve([record,{...record,kpi85PerMinute:4}]).rate,null,'conflicting duplicates stay unresolved');
assert.equal(resolve([record,{...record,step:'4/5'}]).rate,null,'mixed blank and explicit steps are not a blanket fallback');
assert.equal(resolve([{...record,step:'3/4'}]).rate,null,'fraction denominators matter');
assert.equal(resolve([{...record,step:'3/5'}],{...log,step:'3'}).rate,2.975);
assert.equal(resolve([{...record,step:'3/5'},{...record,step:'3/4'}],{...log,step:'3'}).rate,null);
assert.equal(resolve([{...record,step:'3/5'},{...record,step:'4/5'}],{...log,step:''}).rate,null);
assert.equal(resolve([{...record,step:'2/3'}],{...log,step:'2-1/3'}).rate,null,'substeps stay distinct');
assert.equal(resolve([{...record,kpi85PerMinute:undefined}]).rate,null);
assert.equal(match(null,[machine],85)(log).rate,null);
assert.ok(Math.abs(resolve([record],log,100).rate-3.5)<1e-9);
assert.ok(Math.abs(resolve([record]).rate*120-357)<1e-9,'two production hours have target 357, not a full-shift target');
console.log('Capacity matching regression checks passed');
