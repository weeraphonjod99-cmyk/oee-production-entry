import assert from 'node:assert/strict';
import {defectStatistics,groupDefects,defectCsv,searchDefects,type DefectFilters} from '../src/lib/defectStatistics';
import {searchProduction,searchPartKey} from '../src/lib/productionSearch';
const a:any={id:'a',date:'2026-10-01',machineId:'m1',machineName:'Machine 1',partNo:'A',productName:'Part A',step:'1',shift:'D',goodQty:90,ngQty:10,testQty:500,note:'=1+1'};
const b={...a,id:'b',date:'2026-10-02',machineId:'m2',machineName:'Machine 2',step:'2',goodQty:990,ngQty:10};
const total=defectStatistics([a,b]);
assert.equal(total.total,1100);assert.equal(total.ng,20);assert.equal(total.rate,20/1100*100,'weighted ratio excludes test quantities');assert.equal(total.affected,2);
assert.equal(defectStatistics([{...a,goodQty:0,ngQty:0}]).rate,null);
assert.equal(defectStatistics([{...a,ngQty:0}]).rate,0);
assert.equal(defectStatistics([{...a,goodQty:0}]).rate,100);
const invalid=[{...a,ngQty:-1},{...a,goodQty:NaN},{...a,ngQty:null},{...a,goodQty:''}];
assert.equal(defectStatistics([a,...invalid]).invalid,4);assert.equal(defectStatistics([a,...invalid]).ng,10);
assert.equal(groupDefects([a,b],'part').length,2,'steps remain separate');
assert.equal(groupDefects([a,b],'date').reduce((s,r)=>s+r.ng,0),total.ng);
assert.equal(groupDefects([a,b],'machine').reduce((s,r)=>s+r.good,0),total.good);
const f={machine:'m1',part:searchPartKey(a),from:a.date,to:a.date,shift:'D',query:''};
assert.deepEqual(searchProduction([a,b],f).map(l=>l.id),['a']);
assert.equal(searchProduction([a,b],{...f,from:'2026-10-03'}).length,0);
assert.ok(defectCsv([a]).includes('"\'=1+1"'),'CSV notes do not execute spreadsheet formulas');
assert.equal(defectStatistics([]).rate,null);
console.log('Defect statistics: weighted rates, test exclusion, invalid and zero quantities, grouping reconciliation, filters and CSV safety passed');
const multi:DefectFilters={machineIds:[],partKeys:[],from:'',to:'',shift:'',query:''};
const c={...a,id:'c',machineId:'m3',partNo:'C'};
assert.equal(searchDefects([a,b,c],multi).length,3,'empty selections mean all');
assert.deepEqual(searchDefects([a,b,c],{...multi,machineIds:['m1','m2'],partKeys:[searchPartKey(a),searchPartKey(b)]}).map(l=>l.id),['b','a'],'OR inside each selection, AND between machine and part');
assert.deepEqual(searchDefects([a,b,c],{...multi,machineIds:['m1'],partKeys:[searchPartKey(b)]}),[],'incompatible retained selections do not broaden results');
assert.equal(searchDefects([a,b,c],{...multi,machineIds:['m1','m1']}).length,1,'duplicate selection does not duplicate production');
assert.equal(searchDefects([a,b,c],{...multi,machineIds:['m1','m2'],from:'2026-10-02',to:'2026-10-02'}).length,1);
assert.equal(defectStatistics(searchDefects([a,b,c],{...multi,machineIds:['m1','m2']})).ng,20);
console.log('Multiple machine and part selections: union, intersection, date scope and totals passed');
